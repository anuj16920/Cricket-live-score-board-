function makeSquad(
  prefix: string,
  players: Array<{
    name: string;
    role: Player['role'];
    bat: string;
    bowl?: string;
    c?: boolean;
    wk?: boolean;
    sub?: boolean;
  }>
): Player[] {
  return players.map((p, idx) => {
    const parts = p.name.split(' ');
    const shortName = parts.length > 1 ? `${parts[0][0]} ${parts.slice(1).join(' ')}` : p.name;
    return {
      id: `${prefix}-p${idx + 1}`,
      name: p.name,
      shortName,
      role: p.role,
      battingStyle: p.bat,
      bowlingStyle: p.bowl,
      isCaptain: Boolean(p.c),
      isWicketkeeper: Boolean(p.wk),
      isSubstitute: Boolean(p.sub),
    };
  });
}

