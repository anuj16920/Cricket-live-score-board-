function buildOverProgress(perOverRuns: number[], wicketOvers: Record<number, number>): OverProgressPoint[] {
  let cumulative = 0;
  let wickets = 0;
  return perOverRuns.map((runs, idx) => {
    const over = idx + 1;
    cumulative += runs;
    wickets += wicketOvers[over] ?? 0;
    return { over, runs, cumulativeRuns: cumulative, wickets };
  });
}

